type Values = Record<string, string | number>;
type Translator = (key: TranslationKey, values?: Values) => string;

export function translate(language: AppLanguage, key: TranslationKey, values: Values = {}): string {
  const template = (language === "en-US" ? enUS : zhCN)[key];
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

const I18nContext = createContext<{ language: AppLanguage; t: Translator }>({
  language: "zh-CN",
  t: (key, values) => translate("zh-CN", key, values),
});

export function I18nProvider({ language, children }: { language: AppLanguage; children: ReactNode }) {
  return (
    <I18nContext.Provider value={{ language, t: (key, values) => translate(language, key, values) }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
